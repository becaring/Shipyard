"""Render the canonical XDK fixed-arity variant header."""
MAX=19

def variant_header():
    names=[f'T{i}' for i in range(MAX)]
    params=', '.join('class '+n for n in names)
    args=', '.join(names)
    defaults=', '.join('class '+n+(f' = value_detail::absent<{i}>' if i else '') for i,n in enumerate(names))
    sizes='sizeof(T0)'; aligns='std::alignment_of<T0>::value'
    for n in names[1:]:
        sizes=f'value_detail::maximum<{sizes},sizeof({n})>::value'
        aligns=f'value_detail::maximum<{aligns},std::alignment_of<{n}>::value>::value'
    lines=['// Generated by xbox360_platform.value_types. Do not edit.','#ifndef XBOX_COMPAT_VARIANT_H','#define XBOX_COMPAT_VARIANT_H','#include "common.h"','namespace xbox_compat {',f'template<{defaults}> class variant {{',f'    enum {{ storage_size = {sizes}, storage_alignment = {aligns} }};',
    '    typedef typename std::aligned_storage<storage_size,storage_alignment>::type storage_type;',
    '    typedef char alignment_check[(std::alignment_of<storage_type>::value >= storage_alignment)?1:-1];',
    '    storage_type storage_;','    std::size_t index_;']
    unique=' && '.join(f'!std::is_same<T{i},T{j}>::value' for i in range(MAX) for j in range(i+1,MAX))
    # XDK does not discard the ctor reliably for a decltype(select(...)) default
    # parameter. Use the exact existing candidate predicates as an enable_if
    # gate; selection itself remains the existing overload set.
    viable=' || '.join(f'(std::is_convertible<U,{n}>::value && value_detail::nonnarrowing<U,{n}>::value)' for n in names)
    lines += [f'    typedef char unique_alternatives[{unique}?1:-1];']
    for i,n in enumerate(names):
        lines += [f'    template<class U> static typename std::enable_if<std::is_convertible<U,{n}>::value && value_detail::nonnarrowing<U,{n}>::value,value_detail::choice<{i},{n}> >::type select({n});']
    lines += ['    template<class U> struct selection { typedef decltype(variant::template select<U>(value_detail::declval<U>())) type; };',
    '    template<class T> T* ptr() { return reinterpret_cast<T*>(&storage_); }',
    '    template<class T> const T* ptr() const { return reinterpret_cast<const T*>(&storage_); }',
    '    template<class T,class U> void construct(U&& value,std::size_t index) {',
    '        ::new(static_cast<void*>(&storage_)) T(value_detail::forward<U>(value)); index_=index;',
    '    }',
    '    void destroy() { std::size_t old=index_;index_=variant_npos;switch(old) {']
    lines += [f'        case {i}: ptr<{n}>()->~{n}();break;' for i,n in enumerate(names)]
    lines += ['        default:break;','    }}',
    '    template<class T> void copy_assign_alternative(const variant& other,std::size_t index) {',
    '        if(index_==index) { *ptr<T>()=*other.ptr<T>();return; }',
    '        if(is_nothrow_copy<T>::value || !is_nothrow_move<T>::value) { destroy();construct<T>(*other.ptr<T>(),index); }',
    '        else { T temporary(*other.ptr<T>());destroy();construct<T>(value_detail::move(temporary),index); }',
    '    }',
    '    template<class T,class U> void assign_converted(U&& value,std::size_t index) {',
    '        if(index_==index) { *ptr<T>()=value_detail::forward<U>(value);return; }',
    '        if(value_detail::nothrow_conversion<T,U>::value || !is_nothrow_move<T>::value) { destroy();construct<T>(value_detail::forward<U>(value),index); }',
    '        else { T temporary(value_detail::forward<U>(value));destroy();construct<T>(value_detail::move(temporary),index); }',
    '    }',
    'public:',
    '    template<class U> struct index_of { enum { value = '+''.join(f'std::is_same<U,{n}>::value ? {i} : ' for i,n in enumerate(names))+'-1 }; };',
    '    variant():index_(variant_npos) { ::new(static_cast<void*>(&storage_)) T0();index_=0; }',
    '    variant(const variant& other):index_(variant_npos) { switch(other.index_) {']
    lines += [f'        case {i}: construct<{n}>(*other.ptr<{n}>(),{i});break;' for i,n in enumerate(names)]
    lines += ['        default:break;','    }}','    variant(variant&& other):index_(variant_npos) { switch(other.index_) {']
    lines += [f'        case {i}: construct<{n}>(value_detail::move(*other.ptr<{n}>()),{i});break;' for i,n in enumerate(names)]
    lines += ['        default:break;','    }}',
    '    template<class U> variant(U&& value,typename std::enable_if<!std::is_same<typename value_detail::decay<U>::type,variant>::value && ('+viable+'),int>::type = 0):index_(variant_npos) {',
    '        typedef typename selection<U>::type selected;construct<typename selected::type>(value_detail::forward<U>(value),selected::index);',
    '    }',
    '    ~variant() { destroy(); }',
    '    variant& operator=(const variant& other) {',
    '        if(this==&other)return *this;',
    '        switch(other.index_) {']
    lines += [f'        case {i}: copy_assign_alternative<{n}>(other,{i});break;' for i,n in enumerate(names)]
    lines += ['        default:destroy();break;','        }return *this;','    }',
    '    variant& operator=(variant&& other) {',
    '        if(this==&other)return *this;',
    '        switch(other.index_) {']
    lines += [f'        case {i}: if(index_=={i}) *ptr<{n}>()=value_detail::move(*other.ptr<{n}>());else {{ destroy();construct<{n}>(value_detail::move(*other.ptr<{n}>()),{i}); }}break;' for i,n in enumerate(names)]
    lines += ['        default:destroy();break;','        }return *this;','    }',
    '    template<class U> typename std::enable_if<!std::is_same<typename value_detail::decay<U>::type,variant>::value,variant&>::type operator=(U&& value) {',
    '        typedef typename selection<U>::type selected;assign_converted<typename selected::type>(value_detail::forward<U>(value),selected::index);return *this;',
    '    }',
    '    std::size_t index() const { return index_; }',
    '    bool valueless_by_exception() const { return index_==variant_npos; }',
    '    template<class U> U& access() { typedef char present[index_of<U>::value>=0?1:-1];if(index_!=static_cast<std::size_t>(index_of<U>::value))throw bad_variant_access();return *ptr<U>(); }',
    '    template<class U> const U& access() const { typedef char present[index_of<U>::value>=0?1:-1];if(index_!=static_cast<std::size_t>(index_of<U>::value))throw bad_variant_access();return *ptr<U>(); }',
    '};']
    for qualifier,result,expression in [('&','U&','value.template access<U>()'),('const&','const U&','value.template access<U>()'),('&&','U&&','value_detail::move(value.template access<U>())'),('const&&','const U&&','value_detail::move(value.template access<U>())')]:
        cv='const ' if qualifier.startswith('const') else ''; ref=qualifier.replace('const','')
        lines += [f'template<class U,{params}> {result} get({cv}variant<{args}>{ref} value) {{ return {expression}; }}']
    lines += [f'template<class U,{params}> bool holds_alternative(const variant<{args}>& value) {{',f'    typedef variant<{args}> V;typedef char present[V::template index_of<U>::value>=0?1:-1];return value.index()==static_cast<std::size_t>(V::template index_of<U>::value);','}','}','#endif','']
    return '\n'.join(lines)
